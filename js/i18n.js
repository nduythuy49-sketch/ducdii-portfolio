export function getCurrentLang() {
  return localStorage.getItem("preferred_lang") || "vi";
}

export function setLanguage(lang) {
  localStorage.setItem("preferred_lang", lang);
  document.documentElement.lang = lang;
  applyTranslations(lang);
}

export function applyTranslations(lang = getCurrentLang()) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.vi;
  
  // Update all elements with data-i18n attribute
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Update placeholder attribute for input / textarea with data-i18n-ph
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const key = el.getAttribute("data-i18n-ph");
    if (dict[key]) {
      el.setAttribute("placeholder", dict[key]);
    }
  });

  // Update language button display
  const langBtn = document.getElementById("langToggleBtn");
  if (langBtn) {
    langBtn.innerHTML = lang === "vi" 
      ? '<span class="active-lang">VI</span> / <span>EN</span>' 
      : '<span>VI</span> / <span class="active-lang">EN</span>';
  }
}
